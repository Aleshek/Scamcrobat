def text(page, rect, content, font=REGULAR, size=11, color=INK, align=0, lineheight=1.45):
    tw = pymupdf.TextWriter(page.rect)
    tw.fill_textbox(pymupdf.Rect(rect), content, font=font, fontsize=size, align=align, lineheight=lineheight)
    tw.write_text(page, color=color)


def heading(page, number, title, y=MARGIN + 20):
    page.draw_rect(pymupdf.Rect(MARGIN, y - 18, MARGIN + 4, y + 6), color=None, fill=TEAL)
    text(page, (MARGIN + 16, y - 22, page.rect.width - MARGIN, y + 14), f"{number}  {title}", font=BOLD, size=22)
    return y + 40


def paragraphs(page, items, y, width=None):
    right = (width or page.rect.width) - MARGIN
    for p in items:
        tw = pymupdf.TextWriter(page.rect)
        rest = tw.fill_textbox(pymupdf.Rect(MARGIN, y, right, y + 400), p, font=REGULAR, fontsize=11.5, lineheight=1.5)
        tw.write_text(page, color=INK)
        y = tw.last_point.y + 16 if not rest else y + 400
    return y


def footer(page, lang, number):
    w, h = page.rect.width, page.rect.height
    page.draw_line((MARGIN, h - 48), (w - MARGIN, h - 48), color=(0.86, 0.87, 0.9), width=0.7)
    text(page, (MARGIN, h - 42, w - MARGIN, h - 24), TEXT[lang]["title"], size=8.5, color=MUTED)
    text(page, (MARGIN, h - 42, w - MARGIN, h - 24), str(number), size=8.5, color=MUTED, align=2)


def build(lang: str) -> pymupdf.Document:
    t = TEXT[lang]
    doc = pymupdf.open()

    # Cover
    page = doc.new_page(width=A4[0], height=A4[1])
    page.draw_rect(page.rect, color=None, fill=DARK)
    page.draw_rect(pymupdf.Rect(0, 520, A4[0], 528), color=None, fill=TEAL)
    for i, (x, y, r) in enumerate([(430, 210, 70), (480, 300, 38), (380, 320, 24)]):
        page.draw_circle((x, y), r, color=None, fill=BARS[i + 1], fill_opacity=0.85)
    text(page, (MARGIN, 380, A4[0] - MARGIN, 450), t["title"], font=BOLD, size=48, color=(1, 1, 1))
    text(page, (MARGIN, 450, A4[0] - 120, 510), t["subtitle"], size=15, color=(0.8, 0.83, 0.87))
    text(page, (MARGIN, 760, A4[0] - MARGIN, 790), t["edition"], size=10, color=(0.6, 0.64, 0.7))

    # 1 Introduction
    page = doc.new_page(width=A4[0], height=A4[1])
    y = heading(page, 1, t["chapters"][0])
    paragraphs(page, t["intro"], y)
    footer(page, lang, 2)

    # 2 Intelligence + chart
    page = doc.new_page(width=A4[0], height=A4[1])
    y = heading(page, 2, t["chapters"][1])
    y = paragraphs(page, t["intel"], y) + 20
    text(page, (MARGIN, y, A4[0] - MARGIN, y + 20), t["chart"], font=BOLD, size=12)
    base = y + 250
    values = [12, 19, 27, 22, 31, 24]
    bar_w = 46
    for i, v in enumerate(values):
        x = MARGIN + 20 + i * (bar_w + 24)
        top = base - v * 6.5
        page.draw_rect(pymupdf.Rect(x, top, x + bar_w, base), color=None, fill=BARS[i % len(BARS)])
        text(page, (x - 6, top - 18, x + bar_w + 6, top - 2), str(v), size=10, color=MUTED, align=1)
        text(page, (x - 6, base + 6, x + bar_w + 6, base + 22), t["months"][i], size=10, color=MUTED, align=1)
    page.draw_line((MARGIN, base), (A4[0] - MARGIN, base), color=(0.7, 0.72, 0.76), width=0.8)
    footer(page, lang, 3)

    # 3 Species table (landscape)
    page = doc.new_page(width=A4[1], height=A4[0])
    y = heading(page, 3, t["chapters"][2])
    cols = [MARGIN, MARGIN + 190, MARGIN + 290, MARGIN + 530, A4[1] - MARGIN]
    page.draw_rect(pymupdf.Rect(cols[0], y, cols[-1], y + 30), color=None, fill=(0.93, 0.97, 0.96))
    for c, label in enumerate(t["table_head"]):
        text(page, (cols[c] + 10, y + 8, cols[c + 1], y + 26), label, font=BOLD, size=11, color=TEAL)
    y += 30
    for r, row in enumerate(t["table"]):
        if r % 2:
            page.draw_rect(pymupdf.Rect(cols[0], y, cols[-1], y + 34), color=None, fill=(0.97, 0.97, 0.98))
        for c, cell in enumerate(row):
            text(page, (cols[c] + 10, y + 10, cols[c + 1] - 6, y + 30), cell, font=BOLD if c == 0 else REGULAR, size=11)
        y += 34
    footer(page, lang, 4)

    # 4 Watching
    page = doc.new_page(width=A4[0], height=A4[1])
    y = heading(page, 4, t["chapters"][3])
    text(page, (MARGIN, y, A4[0] - MARGIN, y + 20), t["tips_title"], font=BOLD, size=13)
    y += 34
    for i, tip in enumerate(t["tips"], 1):
        page.draw_circle((MARGIN + 11, y + 7), 11, color=None, fill=TEAL)
        text(page, (MARGIN, y, MARGIN + 22, y + 16), str(i), font=BOLD, size=10, color=(1, 1, 1), align=1)
        text(page, (MARGIN + 34, y - 1, A4[0] - MARGIN, y + 40), tip, size=11.5)
        y += 38
    footer(page, lang, 5)

    # 5 Notes
    page = doc.new_page(width=A4[0], height=A4[1])
    y = heading(page, 5, t["chapters"][4])
    paragraphs(page, [t["notes"]], y)
    footer(page, lang, 6)

    doc.set_toc([[1, t["title"], 1]] + [[1, f"{i + 1}  {c}", i + 2] for i, c in enumerate(t["chapters"])])
    doc.set_metadata({"title": f"{t['title']} – {t['subtitle']}"})
    return doc


for lang in TEXT:
    out = OUT / f"demo-{lang}.pdf"
    doc = build(lang)
    doc.subset_fonts()
    doc.save(out, garbage=4, deflate=True)
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size // 1024} kB, {doc.page_count} pages")
